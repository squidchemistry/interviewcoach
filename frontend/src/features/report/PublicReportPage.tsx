import { useQuery } from '@tanstack/react-query';
import { Link, useParams } from 'react-router-dom';
import { publicApi } from '../../api/endpoints';
import { ApiError } from '../../api/http';
import { DifficultyBadge } from '../../components/ui/badges';
import { Alert } from '../../components/ui/form';
import { PageSpinner } from '../../components/ui/PageSpinner';
import { StatusPage } from '../../components/ui/StatusPage';
import { MODE_LABEL, ROLE_LABEL, formatDate } from '../../lib/labels';
import { describeError } from '../auth/errorMessages';
import { CompetencyBar, ScoreHero, StrengthsGaps } from './ReportParts';

/** Anonymised, read-only report opened from a share link. Works without signing in. */
export function PublicReportPage() {
  const { token = '' } = useParams();
  const report = useQuery({ queryKey: ['public-report', token], queryFn: () => publicApi.report(token), retry: false });

  return (
    <div className="flex min-h-screen flex-col">
      <header className="border-b-3 border-ink bg-surface px-4 py-3 sm:px-6">
        <Link to="/" className="flex items-center gap-2 font-bold">
          <span aria-hidden="true" className="grid h-9 w-9 place-items-center border-3 border-ink bg-nb-yellow font-mono text-lg text-[#0a0a0a]">
            AI
          </span>
          <span className="text-lg tracking-tight">Interview Coach</span>
        </Link>
      </header>
      <main id="main" className="flex-1">
        {report.isPending ? (
          <PageSpinner label="Loading the shared report" />
        ) : report.isError ? (
          report.error instanceof ApiError && report.error.status === 404 ? (
            <StatusPage code="404" title="Link unavailable" message="This shared report doesn't exist, has expired or was revoked." />
          ) : (
            <div className="mx-auto max-w-3xl px-4 py-10">
              <Alert>{describeError(report.error)}</Alert>
            </div>
          )
        ) : (
          <div className="mx-auto max-w-5xl space-y-8 px-4 py-10 sm:px-6">
            <div>
              <p className="nb-badge mb-3 bg-nb-green">Shared mock-interview report</p>
              <h1 className="nb-heading text-3xl sm:text-4xl">
                {report.data.candidateFirstName}'s {MODE_LABEL[report.data.mode] ?? report.data.mode} interview
              </h1>
              <p className="mt-2 font-medium text-muted">
                {report.data.targetRole && <>{ROLE_LABEL[report.data.targetRole]} · </>}
                {report.data.company && <>{report.data.company} · </>}
                {formatDate(report.data.completedAt)}
              </p>
            </div>
            <ScoreHero title="Overall score" score={report.data.overallScore} confidence={report.data.confidence} summary={report.data.summary} />
            {report.data.competencies.length > 0 && (
              <section aria-labelledby="public-competencies" className="nb-card space-y-5 p-6">
                <h2 id="public-competencies" className="nb-heading text-2xl">
                  Competencies
                </h2>
                {report.data.competencies.map((c) => (
                  <CompetencyBar key={c.competency} label={c.label} score={c.score} lowConfidence={c.lowConfidence} />
                ))}
              </section>
            )}
            <StrengthsGaps strengths={report.data.strengths} gaps={report.data.gaps} />
            {report.data.questions.length > 0 && (
              <section aria-labelledby="public-questions" className="nb-card overflow-x-auto">
                <h2 id="public-questions" className="nb-heading p-5 text-2xl">
                  Questions
                </h2>
                <table className="nb-table text-sm">
                  <thead>
                    <tr>
                      <th scope="col">#</th>
                      <th scope="col">Question</th>
                      <th scope="col">Difficulty</th>
                      <th scope="col">Score</th>
                    </tr>
                  </thead>
                  <tbody>
                    {report.data.questions.map((q) => (
                      <tr key={q.position}>
                        <td className="font-mono">{q.position + 1}</td>
                        <td className="font-bold">{q.title}</td>
                        <td>
                          <DifficultyBadge difficulty={q.difficulty} />
                        </td>
                        <td className="font-mono font-bold">{q.turnScore !== undefined ? `${q.turnScore}/10` : '—'}</td>
                      </tr>
                    ))}
                  </tbody>
                </table>
              </section>
            )}
            <p className="font-mono text-xs text-muted">
              Practice tool, not a hiring assessment. Generated by AI Interview Coach.
            </p>
          </div>
        )}
      </main>
    </div>
  );
}

export default PublicReportPage;
